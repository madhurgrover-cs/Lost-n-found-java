import java.awt.BorderLayout;
import java.awt.FlowLayout;
import java.awt.GridLayout;
import java.sql.SQLException;
import java.util.List;
import javax.swing.BorderFactory;
import javax.swing.JButton;
import javax.swing.JComboBox;
import javax.swing.JFrame;
import javax.swing.JLabel;
import javax.swing.JOptionPane;
import javax.swing.JPanel;
import javax.swing.JScrollPane;
import javax.swing.JTable;
import javax.swing.JTextField;
import javax.swing.ListSelectionModel;
import javax.swing.SwingUtilities;
import javax.swing.table.DefaultTableModel;

public class LostFoundApp extends JFrame {

    private final ItemDAO dao = new ItemDAO();

  
    private final JTextField idField = new JTextField();
    private final JTextField nameField = new JTextField();
    private final JComboBox<String> categoryBox = new JComboBox<>(new String[] {
            "Electronics", "Books", "Accessories", "Clothing", "Keys", "ID Card", "Bags", "Other" });
    private final JTextField locationField = new JTextField();
    private final JTextField descriptionField = new JTextField();
    private final JComboBox<String> statusBox = new JComboBox<>(new String[] { "Lost", "Found", "Returned" });
    private final JTextField searchField = new JTextField(15);

   
    private final DefaultTableModel tableModel = new DefaultTableModel(
            new String[] { "ID", "Name", "Category", "Location", "Description", "Status", "Reported On" }, 0) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false; // the table is read-only; edit through the form instead
        }
    };
    private final JTable table = new JTable(tableModel);

    public LostFoundApp() {
        setTitle("Campus Lost & Found Manager");
        setSize(950, 550);
        setDefaultCloseOperation(JFrame.EXIT_ON_CLOSE);
        setLocationRelativeTo(null); // centre on screen
        setLayout(new BorderLayout(10, 10));

      
        JPanel searchPanel = new JPanel(new FlowLayout(FlowLayout.LEFT));
        JButton searchButton = new JButton("Search");
        JButton showAllButton = new JButton("Show All");
        searchPanel.add(new JLabel("Search by name or ID:"));
        searchPanel.add(searchField);
        searchPanel.add(searchButton);
        searchPanel.add(showAllButton);
        add(searchPanel, BorderLayout.NORTH);

       
        idField.setEditable(false); // the ID is generated by MySQL, users cannot type it
        JPanel formPanel = new JPanel(new GridLayout(6, 2, 5, 8));
        formPanel.setBorder(BorderFactory.createTitledBorder("Item Details"));
        formPanel.add(new JLabel("ID (auto):"));
        formPanel.add(idField);
        formPanel.add(new JLabel("Item Name *"));
        formPanel.add(nameField);
        formPanel.add(new JLabel("Category *"));
        formPanel.add(categoryBox);
        formPanel.add(new JLabel("Location *"));
        formPanel.add(locationField);
        formPanel.add(new JLabel("Description"));
        formPanel.add(descriptionField);
        formPanel.add(new JLabel("Status *"));
        formPanel.add(statusBox);

        JPanel buttonPanel = new JPanel(new GridLayout(5, 1, 5, 5));
        JButton addButton = new JButton("Add Item");
        JButton updateButton = new JButton("Update Item");
        JButton returnedButton = new JButton("Mark as Returned");
        JButton deleteButton = new JButton("Delete Item");
        JButton clearButton = new JButton("Clear Form");
        buttonPanel.add(addButton);
        buttonPanel.add(updateButton);
        buttonPanel.add(returnedButton);
        buttonPanel.add(deleteButton);
        buttonPanel.add(clearButton);

        JPanel leftPanel = new JPanel(new BorderLayout(5, 10));
        leftPanel.setBorder(BorderFactory.createEmptyBorder(0, 10, 10, 0));
        leftPanel.add(formPanel, BorderLayout.NORTH);
        leftPanel.add(buttonPanel, BorderLayout.CENTER);
        add(leftPanel, BorderLayout.WEST);

       
        table.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        JScrollPane scrollPane = new JScrollPane(table);
        scrollPane.setBorder(BorderFactory.createTitledBorder("Reported Items"));
        add(scrollPane, BorderLayout.CENTER);

       
        addButton.addActionListener(e -> addItem());
        updateButton.addActionListener(e -> updateItem());
        returnedButton.addActionListener(e -> markReturned());
        deleteButton.addActionListener(e -> deleteItem());
        clearButton.addActionListener(e -> clearForm());
        searchButton.addActionListener(e -> searchItems());
        showAllButton.addActionListener(e -> loadAllItems());
        searchField.addActionListener(e -> searchItems()); 

       
        table.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                fillFormFromSelectedRow();
            }
        });

        loadAllItems(); 
    }



    private void addItem() {
        if (!validateForm()) {
            return;
        }
        try {
            dao.addItem(nameField.getText().trim(), (String) categoryBox.getSelectedItem(),
                    locationField.getText().trim(), descriptionField.getText().trim(),
                    (String) statusBox.getSelectedItem());
            JOptionPane.showMessageDialog(this, "Item added successfully.");
            clearForm();
            loadAllItems();
        } catch (SQLException e) {
            showDatabaseError(e);
        }
    }

    private void updateItem() {
        Integer id = getSelectedId();
        if (id == null || !validateForm()) {
            return;
        }
        try {
            int rows = dao.updateItem(id, nameField.getText().trim(), (String) categoryBox.getSelectedItem(),
                    locationField.getText().trim(), descriptionField.getText().trim(),
                    (String) statusBox.getSelectedItem());
            showResult(rows, "Item updated successfully.");
        } catch (SQLException e) {
            showDatabaseError(e);
        }
    }

    private void markReturned() {
        Integer id = getSelectedId();
        if (id == null) {
            return;
        }
        try {
            int rows = dao.markReturned(id);
            showResult(rows, "Item marked as Returned.");
        } catch (SQLException e) {
            showDatabaseError(e);
        }
    }

    private void deleteItem() {
        Integer id = getSelectedId();
        if (id == null) {
            return;
        }
        int choice = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete item " + id + "?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            int rows = dao.deleteItem(id);
            showResult(rows, "Item deleted successfully.");
        } catch (SQLException e) {
            showDatabaseError(e);
        }
    }

    private void searchItems() {
        String keyword = searchField.getText().trim();
        if (keyword.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a name or ID to search.");
            return;
        }
        try {
            List<Item> items = dao.searchItems(keyword);
            showItems(items);
            if (items.isEmpty()) {
                JOptionPane.showMessageDialog(this, "No items found for \"" + keyword + "\".");
            }
        } catch (SQLException e) {
            showDatabaseError(e);
        }
    }

    private void loadAllItems() {
        try {
            showItems(dao.getAllItems());
        } catch (SQLException e) {
            showDatabaseError(e);
        }
    }

   

    
    private void showItems(List<Item> items) {
        tableModel.setRowCount(0);
        for (Item item : items) {
            tableModel.addRow(new Object[] { item.getId(), item.getName(), item.getCategory(),
                    item.getLocation(), item.getDescription(), item.getStatus(), item.getReportedOn() });
        }
    }

    private void fillFormFromSelectedRow() {
        int row = table.getSelectedRow();
        if (row == -1) {
            return;
        }
        idField.setText(tableModel.getValueAt(row, 0).toString());
        nameField.setText((String) tableModel.getValueAt(row, 1));
        categoryBox.setSelectedItem(tableModel.getValueAt(row, 2));
        locationField.setText((String) tableModel.getValueAt(row, 3));
        Object description = tableModel.getValueAt(row, 4);
        descriptionField.setText(description == null ? "" : description.toString());
        statusBox.setSelectedItem(tableModel.getValueAt(row, 5));
    }

    
    private boolean validateForm() {
        String name = nameField.getText().trim();
        String location = locationField.getText().trim();
        String description = descriptionField.getText().trim();
        if (name.isEmpty() || location.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Item Name and Location are required.",
                    "Missing Information", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        if (name.length() > 100 || location.length() > 100 || description.length() > 255) {
            JOptionPane.showMessageDialog(this,
                    "Too long: Name and Location max 100 characters, Description max 255.",
                    "Invalid Input", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        return true;
    }

   
    private Integer getSelectedId() {
        String idText = idField.getText().trim();
        if (idText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select an item from the table first.");
            return null;
        }
        return Integer.parseInt(idText);
    }
 
    private void showResult(int rows, String successMessage) {
        if (rows > 0) {
            JOptionPane.showMessageDialog(this, successMessage);
        } else {
            JOptionPane.showMessageDialog(this, "No item found with that ID. It may have been deleted.");
        }
        clearForm();
        loadAllItems();
    }

    private void showDatabaseError(SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database error: " + e.getMessage()
                        + "\n\nCheck that MySQL is running and the details in DBConnection.java are correct.",
                "Database Error", JOptionPane.ERROR_MESSAGE);
    }

    private void clearForm() {
        idField.setText("");
        nameField.setText("");
        categoryBox.setSelectedIndex(0);
        locationField.setText("");
        descriptionField.setText("");
        statusBox.setSelectedIndex(0);
        table.clearSelection();
    }

    public static void main(String[] args) {
       
        SwingUtilities.invokeLater(() -> new LostFoundApp().setVisible(true));
    }
}

   